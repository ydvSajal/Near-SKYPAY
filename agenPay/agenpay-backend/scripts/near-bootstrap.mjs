// TESTNET bootstrap. Idempotent; safe to re-run. Writes secrets ONLY to .env.near (gitignored),
// so hand-editing .env can never wipe the NEAR keys.
//  1. relayer/sponsor key -> implicit account (id = hex of public key; funded by any transfer)
//  2. top-up: if the relayer is low, create a throwaway account via the testnet helper and sweep its
//     balance into the relayer (helper allows ~10 accounts / 8h / IP; we never try to get around that)
//  3. labeled TEST token (stand-in for USDC; no value), unless NEAR_USDC_CONTRACT is set
// Usage: npm run near:bootstrap
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { config } from 'dotenv';
import { KeyPair, keyToImplicitAddress } from 'near-api-js';
import { NearService } from '../lib/near/NearService.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const nearEnv = path.join(here, '..', '.env.near');
config({ path: [nearEnv, path.join(here, '..', '.env')] });
if (process.env.NEAR_NETWORK && process.env.NEAR_NETWORK !== 'testnet') throw new Error('bootstrap is testnet-only');
process.env.NEAR_NETWORK = 'testnet';

const save = (k, v) => {
  fs.appendFileSync(nearEnv, `${k}=${v}\n`);
  process.env[k] = v;
};
if (!fs.existsSync(nearEnv)) fs.writeFileSync(nearEnv, '# NEAR testnet settings + secrets (generated by npm run near:bootstrap). Never commit.\nNEAR_NETWORK=testnet\nNEAR_RPC_URL=https://test.rpc.fastnear.com\n');

if (!process.env.NEAR_KEY_ENC_SECRET) save('NEAR_KEY_ENC_SECRET', crypto.randomBytes(32).toString('hex'));
if (!process.env.NEAR_RELAYER_ACCOUNT) {
  const kp = KeyPair.fromRandom('ed25519');
  save('NEAR_RELAYER_KEY', kp.toString());
  save('NEAR_RELAYER_ACCOUNT', keyToImplicitAddress(kp.getPublicKey()));
}

const near = new NearService(process.env);
const balance = async (id) => {
  try {
    return BigInt((await near.rpc('query', { request_type: 'view_account', finality: 'optimistic', account_id: id })).amount);
  } catch {
    return 0n;
  }
};
const NEAR = 10n ** 24n;
const fmt = (y) => (Number(y / 10n ** 21n) / 1000).toFixed(3);

let bal = await balance(near.relayerId);
if (bal < 5n * NEAR) {
  try {
    const kp = KeyPair.fromRandom('ed25519');
    const funder = `skypay-fund-${crypto.randomBytes(3).toString('hex')}.testnet`;
    await near.helperCreate(funder, kp.getPublicKey().toString());
    await near.account(funder, kp.toString()).deleteAccount(near.relayerId); // sweep whole balance to relayer
    bal = await balance(near.relayerId);
    console.log(`topped up relayer from helper account ${funder}`);
  } catch (e) {
    console.log(`helper top-up unavailable (${e.message}).`);
  }
}
console.log(`relayer ${near.relayerId}: ${fmt(bal)} NEAR`);
if (bal < 3n * NEAR) {
  console.log(`\n>> Fund the relayer with testnet NEAR (send to ${near.relayerId}), then re-run this script.\n`);
  process.exit(bal === 0n ? 2 : 0);
}

if (!process.env.NEAR_USDC_CONTRACT) {
  const id = `skypay-tusdc-${crypto.randomBytes(3).toString('hex')}.testnet`;
  const kp = KeyPair.fromRandom('ed25519');
  await near.createNamedAccount(id, kp.getPublicKey().toString(), 4n * NEAR);
  const acct = near.account(id, kp.toString());
  await acct.deployContract(fs.readFileSync(path.join(here, '..', 'near-artifacts', 'skypay_test_ft.wasm')));
  await acct.callFunctionRaw({ contractId: id, methodName: 'new', args: {}, gas: 30_000_000_000_000n });
  await acct.deleteKey(kp.getPublicKey().toString()); // immutable; open mint = testnet faucet
  save('NEAR_USDC_CONTRACT', id);
  save('NEAR_USDC_IS_TEST_TOKEN', 'true');
  console.log('TEST token deployed (not real USDC):', id);
}
await near.registerOnToken(near.relayerId); // demo payer holds test tokens
console.log('bootstrap complete; settings in .env.near');
