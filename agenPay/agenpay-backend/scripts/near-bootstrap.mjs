// One-time TESTNET bootstrap: creates the sponsor/relayer account and a labeled TEST token
// (stand-in for USDC; has no value), then appends their ids/keys to .env. Idempotent.
// Usage: npm run near:bootstrap
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { config } from 'dotenv';
import { KeyPair } from 'near-api-js';
import { NearService } from '../lib/near/NearService.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const envPath = path.join(here, '..', '.env');
config({ path: envPath });
if (process.env.NEAR_NETWORK && process.env.NEAR_NETWORK !== 'testnet') throw new Error('bootstrap is testnet-only');

const near = new NearService(process.env);
const rand = () => crypto.randomBytes(3).toString('hex');
const lines = [];

if (!process.env.NEAR_RELAYER_ACCOUNT) {
  const id = `skypay-relayer-${rand()}.testnet`;
  const kp = KeyPair.fromRandom('ed25519');
  await near.helperCreate(id, kp.getPublicKey().toString());
  lines.push(`NEAR_RELAYER_ACCOUNT=${id}`, `NEAR_RELAYER_KEY=${kp.toString()}`);
  console.log('relayer created:', id);
  process.env.NEAR_RELAYER_ACCOUNT = id;
  process.env.NEAR_RELAYER_KEY = kp.toString();
}

if (!process.env.NEAR_USDC_CONTRACT) {
  const id = `skypay-tusdc-${rand()}.testnet`;
  const kp = KeyPair.fromRandom('ed25519');
  await near.helperCreate(id, kp.getPublicKey().toString());
  const acct = near.account(id, kp.toString());
  await acct.deployContract(fs.readFileSync(path.join(here, '..', 'near-artifacts', 'skypay_test_ft.wasm')));
  await acct.callFunctionRaw({ contractId: id, methodName: 'new', args: {}, gas: 30_000_000_000_000n });
  await acct.deleteKey(kp.getPublicKey().toString()); // token is immutable; mint stays open (testnet faucet)
  lines.push(`NEAR_USDC_CONTRACT=${id}`, 'NEAR_USDC_IS_TEST_TOKEN=true');
  console.log('TEST token deployed (not real USDC):', id);
}

if (!/^NEAR_KEY_ENC_SECRET=/m.test(fs.existsSync(envPath) ? fs.readFileSync(envPath, 'utf8') : '')) {
  lines.push(`NEAR_KEY_ENC_SECRET=${crypto.randomBytes(32).toString('hex')}`);
}
if (lines.length) fs.appendFileSync(envPath, '\n# --- NEAR testnet (generated by near:bootstrap) ---\n' + lines.join('\n') + '\n');
console.log(lines.length ? '.env updated' : 'already bootstrapped');
